//! A deterministic mock backend.
//!
//! It streams a fixed script, honours `cancel` and `trim`, and produces
//! plausible-looking timing stats from the *simulated* wall clock. Every stats
//! record is marked `mock: true`; these numbers must never be quoted as real
//! device throughput.
//!
//! The mock never opens the model file. It is a contract fixture for the UI,
//! the JNI bridge and tests, not a model loader.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};
use std::thread;
use std::time::{Duration, Instant};

use sllm_core::EngineConfig;

use crate::engine::Engine;
use crate::error::EngineError;
use crate::stop::StopBuffer;
use crate::types::{
    EngineEvent, EngineState, EngineStats, GenStats, GenerateRequest, Message, ModelRef, TrimLevel,
};

/// Default text streamed by [`MockEngine::new`].
pub const DEFAULT_SCRIPT: &str = "Mock stream: no llama.cpp is loaded. This text is generated by \
sllm-engine to exercise streaming, cancel, and statistics. Every number in these stats is marked \
mock.";

/// Default per-token delay. Roughly 50 tok/s, so the mock feels like a small
/// model on a phone without pretending to be a benchmark.
pub const DEFAULT_TOKEN_DELAY: Duration = Duration::from_millis(20);

/// State guarded by one mutex, read without holding a lock during streaming.
#[derive(Debug)]
struct MockState {
    model: Option<ModelRef>,
    status: EngineState,
    trim: TrimLevel,
    weights: bool,
    requests: u64,
    generated_tokens: u64,
    last: Option<GenStats>,
    pending_trim: TrimLevel,
    pending_unload: bool,
}

impl Default for MockState {
    fn default() -> Self {
        Self {
            model: None,
            status: EngineState::Unloaded,
            trim: TrimLevel::None,
            weights: false,
            requests: 0,
            generated_tokens: 0,
            last: None,
            pending_trim: TrimLevel::None,
            pending_unload: false,
        }
    }
}

impl MockState {
    fn status_for(&self) -> EngineState {
        if self.model.is_none() {
            EngineState::Unloaded
        } else if self.weights {
            EngineState::Ready
        } else {
            EngineState::Trimmed
        }
    }
}

fn lock_state(state: &Mutex<MockState>) -> MutexGuard<'_, MockState> {
    // A panicking sink must not brick the mock; recover the state instead.
    state
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}

fn lock_op(op: &Mutex<()>) -> MutexGuard<'_, ()> {
    op.lock().unwrap_or_else(|poisoned| poisoned.into_inner())
}

/// Mock implementation of [`Engine`].
pub struct MockEngine {
    state: Mutex<MockState>,
    /// Control-plane lock: serialises load/trim/unload against the start of a
    /// generation. Never held while streaming.
    op: Mutex<()>,
    cancel: Arc<AtomicBool>,
    busy: AtomicBool,
    delay: Duration,
    prefill_delay: Duration,
    tokens: Vec<String>,
}

impl std::fmt::Debug for MockEngine {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("MockEngine")
            .field("tokens", &self.tokens.len())
            .field("delay", &self.delay)
            .field("prefill_delay", &self.prefill_delay)
            .finish_non_exhaustive()
    }
}

impl Default for MockEngine {
    fn default() -> Self {
        Self::new()
    }
}

impl MockEngine {
    /// Mock with [`DEFAULT_SCRIPT`] and [`DEFAULT_TOKEN_DELAY`].
    pub fn new() -> Self {
        Self {
            state: Mutex::new(MockState::default()),
            op: Mutex::new(()),
            cancel: Arc::new(AtomicBool::new(false)),
            busy: AtomicBool::new(false),
            delay: DEFAULT_TOKEN_DELAY,
            prefill_delay: Duration::ZERO,
            tokens: split_tokens(DEFAULT_SCRIPT),
        }
    }

    /// Replace the streamed script. It is split into word/space tokens whose
    /// concatenation equals `script`.
    pub fn with_script(mut self, script: impl Into<String>) -> Self {
        let script = script.into();
        self.tokens = split_tokens(&script);
        self
    }

    /// Use an explicit token list. Empty tokens are dropped.
    pub fn with_tokens<I, S>(mut self, tokens: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.tokens = tokens
            .into_iter()
            .map(Into::into)
            .filter(|token| !token.is_empty())
            .collect();
        self
    }

    /// Per-token delay used to simulate decoding. Tests pass
    /// `Duration::ZERO`.
    pub fn with_delay(mut self, delay: Duration) -> Self {
        self.delay = delay;
        self
    }

    /// Delay before prompt processing finishes. Zero by default.
    pub fn with_prefill_delay(mut self, delay: Duration) -> Self {
        self.prefill_delay = delay;
        self
    }

    /// The token list that will be streamed.
    pub fn tokens(&self) -> &[String] {
        &self.tokens
    }

    /// Reconstruct the scripted text.
    pub fn script(&self) -> String {
        self.tokens.concat()
    }

    fn sleep_or_cancel(&self, delay: Duration) -> bool {
        if delay.is_zero() {
            return self.cancel.load(Ordering::Acquire);
        }
        let deadline = Instant::now() + delay;
        while Instant::now() < deadline {
            if self.cancel.load(Ordering::Acquire) {
                return true;
            }
            let left = deadline.saturating_duration_since(Instant::now());
            thread::sleep(left.min(Duration::from_millis(5)));
        }
        self.cancel.load(Ordering::Acquire)
    }
}

impl Engine for MockEngine {
    fn load(&self, model: &ModelRef, config: &EngineConfig) -> Result<(), EngineError> {
        let _op = lock_op(&self.op);
        if self.busy.load(Ordering::Acquire) {
            return Err(EngineError::busy());
        }

        if model.id.trim().is_empty() {
            return Err(EngineError::config("model id is empty"));
        }
        if model.path.as_os_str().is_empty() {
            return Err(EngineError::config("model path is empty"));
        }
        for lora in &model.loras {
            if !lora.scale.is_finite() || !(0.0..=10.0).contains(&lora.scale) {
                return Err(EngineError::config("LoRA scale must be in [0, 10]"));
            }
        }
        config.validate()?;

        let mut state = lock_state(&self.state);
        state.model = Some(model.clone());
        state.status = EngineState::Ready;
        state.trim = TrimLevel::None;
        state.weights = true;
        state.requests = 0;
        state.generated_tokens = 0;
        state.last = None;
        state.pending_trim = TrimLevel::None;
        state.pending_unload = false;
        self.cancel.store(false, Ordering::Release);
        Ok(())
    }

    fn generate(
        &self,
        request: &GenerateRequest,
        sink: &mut dyn FnMut(EngineEvent),
    ) -> Result<GenStats, EngineError> {
        let started = Instant::now();

        // Start gate: reject a concurrent generation without touching the
        // active generation's cancel flag.
        {
            let _op = lock_op(&self.op);
            if self.busy.load(Ordering::Acquire) {
                return Err(EngineError::busy());
            }
            self.cancel.store(false, Ordering::Release);
            self.busy.store(true, Ordering::Release);
        }
        let busy = BusyFlag(&self.busy);

        if let Err(error) = request.validate() {
            return emit_error(sink, error);
        }

        {
            let state = lock_state(&self.state);
            match (&state.model, state.weights) {
                (None, _) => {
                    drop(state);
                    return emit_error(
                        sink,
                        EngineError::no_model("no model loaded; call load first"),
                    );
                }
                (Some(_), false) => {
                    drop(state);
                    return emit_error(
                        sink,
                        EngineError::no_model(
                            "model weights were released by trim(complete); load again",
                        ),
                    );
                }
                (Some(_), true) => {}
            }
        }

        {
            let mut state = lock_state(&self.state);
            state.status = EngineState::Generating;
            state.requests += 1;
        }
        let mut restore = RestoreState {
            state: &self.state,
            armed: true,
        };

        let prompt_tokens = estimate_prompt_tokens(&request.messages);
        sink(EngineEvent::Started { prompt_tokens });

        let mut canceled = self.sleep_or_cancel(self.prefill_delay);
        let prefill_done = Instant::now();

        let max_tokens = request.max_tokens as usize;
        let mut buffer = StopBuffer::new(&request.stop);
        let mut generated = 0usize;
        let mut last_id = 0u32;
        let mut first_token_at = None;

        if !canceled {
            for (index, token) in self.tokens.iter().enumerate() {
                if generated >= max_tokens {
                    break;
                }
                if self.cancel.load(Ordering::Acquire) {
                    canceled = true;
                    break;
                }
                if self.sleep_or_cancel(self.delay) {
                    canceled = true;
                    break;
                }

                generated += 1;
                let id = u32::try_from(index + 1).unwrap_or(u32::MAX);
                last_id = id;
                if first_token_at.is_none() {
                    first_token_at = Some(Instant::now());
                }

                let piece = buffer.push(token);
                if !piece.is_empty() {
                    sink(EngineEvent::Token { text: piece, id });
                }
                if buffer.hit() {
                    break;
                }
            }
        }

        // Flush the part held back for stop-string matching. If a stop string
        // was hit, `finish` returns nothing.
        if generated > 0 {
            let tail = buffer.finish();
            if !tail.is_empty() {
                sink(EngineEvent::Token {
                    text: tail,
                    id: last_id,
                });
            }
        }

        let finished = Instant::now();
        let total_ms = finished.duration_since(started).as_millis() as u64;
        let ttft_ms = first_token_at
            .map(|at| at.duration_since(started).as_millis() as u64)
            .unwrap_or(0);
        let prefill_ms = prefill_done.duration_since(started).as_millis() as u64;
        let decode_ms = first_token_at
            .map(|at| finished.duration_since(at).as_millis() as u64)
            .unwrap_or(0);
        let decoded_tokens = generated.saturating_sub(1);
        let tok_per_s = if decode_ms > 0 {
            (decoded_tokens as f64 * 1000.0 / decode_ms as f64) as f32
        } else if total_ms > 0 {
            (generated as f64 * 1000.0 / total_ms as f64) as f32
        } else {
            0.0
        };

        let stats = GenStats {
            prompt_tokens,
            generated_tokens: generated,
            ttft_ms,
            prefill_ms,
            decode_ms,
            tok_per_s,
            seed: request.seed,
            canceled,
            mock: true,
        };

        {
            let mut state = lock_state(&self.state);
            state.generated_tokens += generated as u64;
            state.last = Some(stats.clone());
            let status = state.status_for();
            state.status = status;

            if state.pending_unload {
                apply_unload(&mut state);
            } else {
                let pending = std::mem::take(&mut state.pending_trim);
                if pending > state.trim {
                    apply_trim(&mut state, pending);
                }
            }
        }
        restore.armed = false;

        sink(EngineEvent::Done {
            stats: stats.clone(),
        });
        drop(busy);
        Ok(stats)
    }

    fn cancel(&self) {
        // Only latch a cancellation for a generation that is actually running;
        // otherwise a stale `cancel` would kill the next request.
        if self.busy.load(Ordering::Acquire) {
            self.cancel.store(true, Ordering::Release);
        }
    }

    fn trim(&self, level: TrimLevel) {
        let _op = lock_op(&self.op);
        if self.busy.load(Ordering::Acquire) {
            let mut state = lock_state(&self.state);
            state.pending_trim = state.pending_trim.max(level);
            return;
        }
        let mut state = lock_state(&self.state);
        apply_trim(&mut state, level);
    }

    fn stats(&self) -> EngineStats {
        let state = lock_state(&self.state);
        EngineStats {
            state: state.status,
            model_id: state.model.as_ref().map(|model| model.id.clone()),
            trim: state.trim,
            needs_reload: state.model.is_some() && !state.weights,
            requests: state.requests,
            generated_tokens: state.generated_tokens,
            last: state.last.clone(),
            mock: true,
        }
    }

    fn unload(&self) {
        let _op = lock_op(&self.op);
        if self.busy.load(Ordering::Acquire) {
            let mut state = lock_state(&self.state);
            state.pending_unload = true;
            return;
        }
        let mut state = lock_state(&self.state);
        apply_unload(&mut state);
    }
}

fn apply_trim(state: &mut MockState, level: TrimLevel) {
    if state.model.is_none() {
        return;
    }
    let effective = state.trim.max(level);
    state.trim = effective;
    if effective == TrimLevel::Complete {
        state.weights = false;
        state.status = EngineState::Trimmed;
    } else if state.weights {
        state.status = EngineState::Ready;
    }
}

fn apply_unload(state: &mut MockState) {
    state.model = None;
    state.status = EngineState::Unloaded;
    state.trim = TrimLevel::None;
    state.weights = false;
    state.pending_trim = TrimLevel::None;
    state.pending_unload = false;
}

fn emit_error(
    sink: &mut dyn FnMut(EngineEvent),
    error: EngineError,
) -> Result<GenStats, EngineError> {
    sink(EngineEvent::from_error(&error));
    Err(error)
}

/// Clears the busy flag even if a sink panics.
struct BusyFlag<'a>(&'a AtomicBool);

impl Drop for BusyFlag<'_> {
    fn drop(&mut self) {
        self.0.store(false, Ordering::Release);
    }
}

/// Restores `Ready`/`Trimmed` if the stream unwinds through a panicking sink.
struct RestoreState<'a> {
    state: &'a Mutex<MockState>,
    armed: bool,
}

impl Drop for RestoreState<'_> {
    fn drop(&mut self) {
        if !self.armed {
            return;
        }
        let mut state = lock_state(self.state);
        let status = state.status_for();
        state.status = status;
    }
}

/// Rough prompt length used by the mock. Real backends use the tokenizer.
fn estimate_prompt_tokens(messages: &[Message]) -> usize {
    if messages.is_empty() {
        return 0;
    }
    messages
        .iter()
        .map(|message| message.content.split_whitespace().count().max(1) + 3)
        .sum()
}

/// Split text into word/whitespace runs; concatenation is lossless.
fn split_tokens(text: &str) -> Vec<String> {
    let mut tokens = Vec::new();
    let mut current = String::new();
    let mut current_is_space = false;

    for ch in text.chars() {
        let is_space = ch.is_whitespace();
        if current.is_empty() {
            current_is_space = is_space;
            current.push(ch);
        } else if is_space == current_is_space {
            current.push(ch);
        } else {
            tokens.push(std::mem::take(&mut current));
            current_is_space = is_space;
            current.push(ch);
        }
    }
    if !current.is_empty() {
        tokens.push(current);
    }
    tokens
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn split_tokens_is_lossless() {
        for text in [
            "",
            "one",
            "one two",
            "  leading and trailing  ",
            "Привет, мир!\nЕщё строка.",
        ] {
            assert_eq!(split_tokens(text).concat(), text);
        }
    }

    #[test]
    fn prompt_estimate_counts_words() {
        assert_eq!(estimate_prompt_tokens(&[]), 0);
        assert_eq!(estimate_prompt_tokens(&[Message::user("one two three")]), 6);
        assert_eq!(
            estimate_prompt_tokens(&[Message::system("x"), Message::user("y z")]),
            9
        );
    }
}
